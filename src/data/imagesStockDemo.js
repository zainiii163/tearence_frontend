export const filterImagesStockDemo = (filters = {}) => {
  let list = [...IMAGES_STOCK_DEMO];
  const search = (filters.search || '').toString().trim().toLowerCase();
  if (search) {
    list = list.filter(
      (img) =>
        img.title.toLowerCase().includes(search) ||
        img.description.toLowerCase().includes(search) ||
        (img.tags || []).some((t) => t.toLowerCase().includes(search))
    );
  }
  if (filters.image_category) {
    const cats = Array.isArray(filters.image_category)
      ? filters.image_category
      : [filters.image_category];
    list = list.filter((img) => cats.includes(img.image_category));
  }
  if (filters.orientation) {
    list = list.filter((img) => img.orientation === filters.orientation);
  }
  if (filters.color_type) {
    list = list.filter((img) => img.color_type === filters.color_type);
  }
  return list;
};
