export function getDemoStoreBySlug(slug) {
  const key = String(slug || '').toLowerCase();
  return DEMO_STORES.find((s) => s.slug === key) || null;
}

export function getDemoStoreProducts(slug) {
  const key = String(slug || '').toLowerCase();
  return DEMO_STORE_PRODUCTS[key] || [];
}

