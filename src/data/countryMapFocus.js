export function getCountryMapFocus(countryName) {
  if (!countryName) return null;
  const direct = COUNTRY_MAP_FOCUS[countryName];
  if (direct) return { name: countryName, ...direct };
  const key = Object.keys(COUNTRY_MAP_FOCUS).find(
    (k) => k.toLowerCase() === String(countryName).toLowerCase()
  );
  return key ? { name: key, ...COUNTRY_MAP_FOCUS[key] } : null;
}
